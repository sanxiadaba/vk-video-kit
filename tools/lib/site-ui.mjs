const THEME = {
  name: 'vk-site',
  type: 'light',
  settings: [
    { settings: { foreground: '#0B0F14', background: '#FFFFFF' } },
    { scope: ['comment', 'punctuation.definition.comment'], settings: { foreground: '#64748B', fontStyle: 'italic' } },
    { scope: ['keyword', 'storage.type', 'storage.modifier'], settings: { foreground: '#1B3FD6' } },
    { scope: ['string', 'string.quoted', 'string.template'], settings: { foreground: '#0A6B57' } },
    { scope: ['constant.numeric', 'constant.language', 'constant.character'], settings: { foreground: '#8A5A00' } },
    { scope: ['entity.name.tag', 'meta.tag'], settings: { foreground: '#0B0F14' } },
    { scope: ['entity.other.attribute-name'], settings: { foreground: '#1B3FD6' } },
    { scope: ['entity.name.function', 'support.function'], settings: { foreground: '#1B3FD6' } },
    { scope: ['punctuation', 'meta.brace'], settings: { foreground: '#64748B' } },
    { scope: ['variable', 'support.variable'], settings: { foreground: '#0B0F14' } },
  ],
};

let highlighterPromise = null;
const LANGS = new Set(['bash', 'html', 'css', 'javascript', 'json', 'text']);

async function highlighter() {
  highlighterPromise ||= createHighlighter({
    themes: [THEME],
    langs: ['bash', 'html', 'css', 'javascript', 'json', 'text'],
  });
  return highlighterPromise;
}

/** 生成期高亮；失败时退回纯代码块，生成不依赖 CDN。 */
export async function highlight(code, lang = 'html') {
  const language = LANGS.has(lang) ? lang : 'text';
  try {
    const h = await highlighter();
    return h.codeToHtml(String(code), { lang: language, theme: 'vk-site' });
  } catch {
    return `<pre class="code plain"><code>${esc(code)}</code></pre>`;
  }
}

/** 带语言标签的代码块。raw 仍由调用方单独保留，复制不读高亮后的 HTML。 */
export async function codeblock(code, lang = 'html', label = '') {
  const html = await highlight(code, lang);
  return `<div class="codeblock">${
    label ? `<div class="codeblock-hd"><span>${esc(label)}</span></div>` : ''
  }${html}</div>`;
}
