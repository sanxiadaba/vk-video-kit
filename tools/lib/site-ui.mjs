      <svg class="search-ico" viewBox="0 0 16 16" width="14" height="14" aria-hidden="true"><circle cx="6.8" cy="6.8" r="5" fill="none" stroke="currentColor"/><path d="m10.6 10.6 3 3" fill="none" stroke="currentColor"/></svg>
