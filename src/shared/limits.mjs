/**
 * 硬性数值：只有一个来源。
 *
 * contract 96/35.5/96），同一页会被判成两个相反的结论。数值是"什么算坏"的定义，
 * 一个定义只能有一处。CSS 里的 token 与这里对齐，由 tests/limits.test.mjs 断言。
 *
 * 观看条件：观众是手机横屏。1920×1080 的帧在手机上实际渲染到
 * 约 780×439（0.406×），所以字号按"缩到 0.4× 还读得动"定：
 *   display 200 / headline 112 / body 56 / caption 48。
 * 0.406× 下分别是 81 / 45 / 23 / 19 设备像素：caption 是地板，正文不小于 body。
 *
 * 对比度分两档，不是一刀切：
 *   · 正文/主墨 7:1 —— 观众要读懂的那一句；
 *   · 标注 4.5:1 —— 只有 ink="muted" 的元数据（地址、刻度、单位），
 *     且按规则它不得承载必要信息（规则写在这里，由 review 与人守）。
 *   0.406× 下 48px 的标注等于 19.5 设备像素，4.5:1 是它与可读性之间的底线；
 *   把它也推到 7:1 会把灰压成黑，层级消失。
 */

export const LIMITS = {
  /** 字号地板（caption：标签 / 单位 / 刻度 / 出处）。手机横屏 0.406× 后约 19.5px。 */
  fontFloor: 48,
  /** tag 档（vk-label variant="tag" / vk-flow 的步骤标签）：caption × 0.75。
   *  它是「块的名字」，比正文小一档，但不是正文，也不该被正文地板判红。 */
  fontTag: 36,
  /** 正文：一整句中文低于它就算排错（body 档，22.7px） */
  fontBody: 56,
  /** 等宽数据（代码 / 表格数字 / 地址）的最低字号 */
  fontData: 56,
  /** 大字：只有大字允许用低一档的对比度（headline 档） */
  fontLarge: 112,

  /** 正文对比度 */
  contrastText: 7,
  /** 标注对比度（ink="muted"，不得承载必要信息） */
  contrastMuted: 4.5,
  /** 大字对比度 */
  contrastLarge: 4.5,
  /**
   * 数据区（代码窗 / 地址格 / 位图）里的等宽文字。
   *
   * 它不是"正文"，也不是"标注"：颜色在这里是编码（字符串绿、运算符蓝、地址灰），
   * 把这些颜色全推到 7:1，代码块会变成一片深灰，编码消失。
   * 所以它按 AA 走 4.5:1 —— 与标注同一条线，理由不同：一个是"不承载信息"，
   * 一个是"用颜色承载信息"。
   */
  contrastData: 4.5,

  /** 安全区（1920×1080 纸）：与 tokens.css 的 --vk-safe-x/y 对齐 */
  safe: { x: 120, y: 96, w: 1680, h: 888 },
};

